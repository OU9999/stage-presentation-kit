'use strict';
const fs=require('node:fs'),path=require('node:path'),os=require('node:os'),crypto=require('node:crypto'),{execFileSync}=require('node:child_process');
const root=path.resolve(__dirname,'../../..');
const temporary=fs.mkdtempSync(path.join(os.tmpdir(),'llm-wiki-foundations-'));
const project=path.join(temporary,'project'),moved=path.join(temporary,'moved');
fs.mkdirSync(path.join(project,'talks'),{recursive:true});
fs.cpSync(path.join(root,'talks/llm-wiki'),path.join(project,'talks/llm-wiki'),{recursive:true});
fs.writeFileSync(path.join(project,'stage.config.json'),JSON.stringify({title:'Independent Wiki Study',theme:'stage',sourceDir:'talks',outputDir:'presentations'}));
function build(folder){return execFileSync(process.execPath,[path.join(root,'scripts/stage.cjs'),'build','--config',path.join(folder,'stage.config.json')],{encoding:'utf8'});}
function hashes(folder,prefix=''){
 const result={};for(const entry of fs.readdirSync(folder,{withFileTypes:true})){const file=path.join(folder,entry.name),name=path.join(prefix,entry.name);if(entry.isDirectory())Object.assign(result,hashes(file,name));else result[name]=crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');}return result;
}
const firstLog=build(project),first=hashes(path.join(project,'presentations'));
fs.renameSync(project,moved);const secondLog=build(moved),second=hashes(path.join(moved,'presentations'));
const changed=[...new Set([...Object.keys(first),...Object.keys(second)])].filter(key=>first[key]!==second[key]);
const result={temporary,moved,files:Object.keys(second).length,changed,firstLog,secondLog,hashes:second};
fs.writeFileSync(path.join(__dirname,'copy-check.json'),JSON.stringify(result,null,2)+'\n');
if(changed.length)throw new Error('Moved project has different generated bytes: '+changed.join(','));
console.log({files:result.files,changed:changed.length});
