import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {prepare} from '../../reusable-layouts-20261028/evidence/browser-helpers.mjs';
const evidence=fileURLToPath(new URL('./',import.meta.url));
const task=await taskSpace(76),page=task.page('p1');
await prepare(page);
await page.goto('http://127.0.0.1:4323/presentations/llm-wiki/index.html?controls=final#6');
await page.waitForSelector('#slideStage .is-active');
console.log(await page.snapshot());
await page.click('[data-action="overview"]');
await page.waitForFunction(()=>!document.getElementById('overviewDialog').hidden);
const overview=await page.evaluate(()=>({count:document.querySelectorAll('#overviewGrid .overview-card').length,links:document.querySelectorAll('#overviewGrid .overview-thumb a').length}));
await page.click('#overviewGrid .overview-card[data-slide="6"]');
await page.waitForFunction(()=>location.hash==='#7'&&document.getElementById('overviewDialog').hidden);
const opened=page.waitForEvent('popup');
await page.click('[data-action="presenter"]');
const popup=await opened;
await popup.waitForFunction(()=>document.querySelectorAll('#presenterCurrent .slide').length===1&&document.querySelectorAll('#presenterNext .slide').length===1);
const presenter=await popup.evaluate(()=>({current:document.querySelector('#presenterCurrent .slide').dataset.index,next:document.querySelector('#presenterNext .slide').dataset.index,links:document.querySelectorAll('#presenterCurrent a,#presenterNext a').length}));
await popup.click('[data-action="next"]');
await page.waitForFunction(()=>location.hash==='#8');
await page.cdp('Page.bringToFront');
await page.keyboard.press('ArrowLeft');
await popup.waitForFunction(()=>document.querySelector('#presenterCurrent .slide')?.dataset.index==='6');
presenter.syncBothDirections=true;
await popup.close();
await page.goto('http://127.0.0.1:4323/presentations/llm-wiki/index.html?controls=final#12');
await page.waitForSelector('#slideStage .is-active');
const links=await page.evaluate(()=>[...document.querySelectorAll('#slideStage .is-active a')].map(a=>({text:a.textContent,href:a.href})));
const attachments=[];
await fs.mkdir(evidence+'downloads',{recursive:true});
for(const link of links){
  const pending=page.waitForEvent('download');
  await page.click('#slideStage .is-active a[href="'+link.href.split('/llm-wiki/')[1]+'"]');
  const download=await pending;
  const filename=link.href.split('/').at(-1);
  await download.saveAs(evidence+'downloads/'+filename);
  const bytes=await fs.readFile(evidence+'downloads/'+filename),text=bytes.toString('utf8');
  const local=await fs.readFile(fileURLToPath(new URL('../../../presentations/llm-wiki/assets/'+filename,import.meta.url)));
  attachments.push({...link,characters:text.length,korean:/[가-힣]/.test(text),title:text.split('\n')[0],sha256:crypto.createHash('sha256').update(bytes).digest('hex'),matchesGenerated:bytes.equals(local)});
}
const result={overview,presenter,attachments};
await fs.writeFile(evidence+'controls.json',JSON.stringify(result,null,2)+'\n');
console.log(result);
if(overview.count!==12||overview.links||presenter.current!=='6'||presenter.next!=='7'||presenter.links||attachments.length!==4||attachments.some(a=>a.characters<1000||!a.korean||!a.matchesGenerated))throw new Error('Control/attachment QA requires review.');
